UPDATE "ValueChainNode" n SET "status_next" = CASE
  WHEN n."status"::text <> 'PROVEN' THEN n."status"::text
  WHEN EXISTS (
    SELECT 1 FROM "EvidenceClaimLink" l JOIN "Evidence" e ON e.id = l."evidenceId"
    WHERE l."valueChainNodeId" = n.id AND l."direction" = 'SUPPORTS'
      AND e."sourceType"::text IN ('OBSERVED_WORKFLOW','PRODUCT_USAGE','CLICKSTREAM','PURCHASE_BEHAVIOR','CRM_DATA','TRANSACTION_RECORDS','FINANCIAL_RECORDS','SYSTEM_LOGS','BOOKING_DATA','POS_DATA','ERP_DATA','SUPPORT_TICKETS','TIME_TRACKING_DATA','PROTOTYPE_TEST','CONCIERGE_TEST','BEFORE_AFTER_TEST','MATCHED_COMPARISON','CONTROLLED_EXPERIMENT','AB_TEST','RANDOMIZED_EXPERIMENT','PRICING_EXPERIMENT','LANDING_PAGE_EXPERIMENT','TECHNICAL_SPIKE','BENCHMARK','DATA_FEASIBILITY_STUDY','INTEGRATION_TEST','LOAD_TEST','SIGNED_LOI','PAID_PILOT','CONTRACT','INVOICE','SUBSCRIPTION_PURCHASE','RENEWAL','EXPANSION')
  ) THEN 'OBSERVED'
  ELSE 'STRONGLY_SUPPORTED' END;
UPDATE "CausalLink" c SET "status_next" = CASE
  WHEN c."status"::text <> 'PROVEN' THEN c."status"::text
  WHEN EXISTS (
    SELECT 1 FROM "EvidenceClaimLink" l JOIN "Evidence" e ON e.id = l."evidenceId"
    WHERE l."causalLinkId" = c.id AND l."direction" = 'SUPPORTS'
      AND e."sourceType"::text IN ('OBSERVED_WORKFLOW','PRODUCT_USAGE','CLICKSTREAM','PURCHASE_BEHAVIOR','CRM_DATA','TRANSACTION_RECORDS','FINANCIAL_RECORDS','SYSTEM_LOGS','BOOKING_DATA','POS_DATA','ERP_DATA','SUPPORT_TICKETS','TIME_TRACKING_DATA','PROTOTYPE_TEST','CONCIERGE_TEST','BEFORE_AFTER_TEST','MATCHED_COMPARISON','CONTROLLED_EXPERIMENT','AB_TEST','RANDOMIZED_EXPERIMENT','PRICING_EXPERIMENT','LANDING_PAGE_EXPERIMENT','TECHNICAL_SPIKE','BENCHMARK','DATA_FEASIBILITY_STUDY','INTEGRATION_TEST','LOAD_TEST','SIGNED_LOI','PAID_PILOT','CONTRACT','INVOICE','SUBSCRIPTION_PURCHASE','RENEWAL','EXPANSION')
  ) THEN 'OBSERVED'
  ELSE 'STRONGLY_SUPPORTED' END;
UPDATE "ValuePath" SET "status_next" = CASE WHEN "status"::text = 'PROVEN' THEN 'STRONGLY_SUPPORTED' ELSE "status"::text END;
UPDATE "Variable" SET "evidenceStatus_next" = CASE WHEN "evidenceStatus"::text = 'PROVEN' THEN 'STRONGLY_SUPPORTED' ELSE "evidenceStatus"::text END;

