-- Backfill: legacy evidence type → source type (same rule as evidence-sources.ts).
UPDATE "Evidence" SET "sourceType" = (CASE "type"::text
  WHEN 'INTERVIEW' THEN 'INTERVIEW'
  WHEN 'SURVEY' THEN 'SURVEY'
  WHEN 'CUSTOMER_QUOTE' THEN 'CUSTOMER_QUOTE'
  WHEN 'FORUM_POST' THEN 'FORUM_POST'
  WHEN 'REDDIT' THEN 'REDDIT_POST'
  WHEN 'REVIEW' THEN 'COMPETITOR_REVIEW'
  WHEN 'COMPETITOR_REVIEW' THEN 'COMPETITOR_REVIEW'
  WHEN 'JOB_POSTING' THEN 'JOB_POSTING'
  WHEN 'SEARCH_SIGNAL' THEN 'MARKET_DATASET'
  WHEN 'MARKET_REPORT' THEN 'INDUSTRY_REPORT'
  ELSE 'OTHER' END)::"EvidenceSourceType"
WHERE "type"::text <> 'EXPERIMENT';

UPDATE "Evidence" e SET "sourceType" = (CASE x."experimentType"::text
  WHEN 'CUSTOMER_INTERVIEW' THEN 'INTERVIEW'
  WHEN 'PRICING_TEST' THEN 'PRICING_EXPERIMENT'
  WHEN 'LANDING_PAGE_TEST' THEN 'LANDING_PAGE_EXPERIMENT'
  WHEN 'CONCIERGE_TEST' THEN 'CONCIERGE_TEST'
  WHEN 'PROTOTYPE_TEST' THEN 'PROTOTYPE_TEST'
  WHEN 'DATA_FEASIBILITY_TEST' THEN 'DATA_FEASIBILITY_STUDY'
  WHEN 'AB_TEST' THEN 'AB_TEST'
  WHEN 'MANUAL_WORKFLOW_TEST' THEN 'CONCIERGE_TEST'
  WHEN 'COHORT_OBSERVATION' THEN 'OBSERVED_WORKFLOW'
  WHEN 'TECHNICAL_SPIKE' THEN 'TECHNICAL_SPIKE'
  WHEN 'RETROSPECTIVE_DATA_ANALYSIS' THEN 'TRANSACTION_RECORDS'
  ELSE 'OTHER' END)::"EvidenceSourceType"
FROM "Experiment" x
WHERE e."experimentId" = x.id AND e."type"::text = 'EXPERIMENT';

-- ClaimType: normalized taxonomy. Map every existing link before swapping the enum.
ALTER TABLE "EvidenceClaimLink" ADD COLUMN "claimType_next" TEXT;
UPDATE "EvidenceClaimLink" SET "claimType_next" = (CASE "claimType"::text
  WHEN 'ICP' THEN 'ICP_EXISTS'
  WHEN 'VARIABLE' THEN 'VARIABLE_IMPORTANCE'
  WHEN 'CURRENT_STATE' THEN 'CURRENT_STATE'
  WHEN 'PAIN' THEN 'PAIN_EXISTS'
  WHEN 'MAGNITUDE' THEN 'MAGNITUDE'
  WHEN 'FREQUENCY' THEN 'PAIN_FREQUENCY'
  WHEN 'ECONOMIC_IMPACT' THEN 'ECONOMIC_IMPACT'
  WHEN 'MECHANISM' THEN 'MECHANISM_FEASIBLE'
  WHEN 'WILLINGNESS_TO_PAY' THEN 'WILLINGNESS_TO_PAY'
  WHEN 'ALTERNATIVE' THEN 'ALTERNATIVE_EXISTS'
  WHEN 'TRIGGER' THEN 'TRIGGER_EXISTS'
  ELSE 'OTHER' END);
UPDATE "EvidenceClaimLink" l SET "claimType_next" = (CASE n."level"::text
  WHEN 'MECHANISM' THEN 'MECHANISM_FEASIBLE'
  WHEN 'CAPABILITY' THEN 'CAPABILITY_EXISTS'
  WHEN 'TRANSFORMATION' THEN 'TRANSFORMATION_OCCURS'
  WHEN 'OPERATIONAL_VALUE' THEN 'OPERATIONAL_VALUE'
  WHEN 'ECONOMIC_VALUE' THEN 'ECONOMIC_VALUE'
  WHEN 'STRATEGIC_OUTCOME' THEN 'STRATEGIC_OUTCOME'
  WHEN 'BUSINESS_OUTCOME' THEN 'BUSINESS_OUTCOME'
  ELSE 'OTHER' END)
FROM "ValueChainNode" n
WHERE l."valueChainNodeId" = n.id AND l."claimType"::text = 'VALUE_CHAIN_NODE';
UPDATE "EvidenceClaimLink" l SET "claimType_next" = (CASE f."level"::text || '>' || t."level"::text
  WHEN 'MECHANISM>CAPABILITY' THEN 'MECHANISM_CAUSES_CAPABILITY'
  WHEN 'CAPABILITY>TRANSFORMATION' THEN 'CAPABILITY_CAUSES_TRANSFORMATION'
  WHEN 'TRANSFORMATION>OPERATIONAL_VALUE' THEN 'TRANSFORMATION_CAUSES_OPERATIONAL_VALUE'
  WHEN 'OPERATIONAL_VALUE>ECONOMIC_VALUE' THEN 'OPERATIONAL_VALUE_CAUSES_ECONOMIC_VALUE'
  WHEN 'ECONOMIC_VALUE>STRATEGIC_OUTCOME' THEN 'ECONOMIC_VALUE_CAUSES_STRATEGIC_OUTCOME'
  WHEN 'STRATEGIC_OUTCOME>BUSINESS_OUTCOME' THEN 'STRATEGIC_OUTCOME_CAUSES_BUSINESS_OUTCOME'
  ELSE 'CAUSAL_EFFECT' END)
FROM "CausalLink" c
JOIN "ValueChainNode" f ON f.id = c."fromNodeId"
JOIN "ValueChainNode" t ON t.id = c."toNodeId"
WHERE l."causalLinkId" = c.id AND l."claimType"::text = 'CAUSAL_LINK';

